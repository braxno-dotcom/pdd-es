def esquema_faq(pagina):
    """Разметка FAQPage: Google показывает такие вопросы прямо в выдаче."""
    partes = []
    for preg, resp in pagina["faq"]:
        partes.append(
            '{"@type":"Question","name":"%s","acceptedAnswer":{"@type":"Answer","text":"%s"}}'
            % (preg.replace('"', "'"), resp.replace('"', "'"))
        )
    return ('{"@context":"https://schema.org","@type":"FAQPage","mainEntity":[%s]}'
            % ",".join(partes))


def faq_html(pagina):
    filas = []
    for preg, resp in pagina["faq"]:
        filas.append("      <b>%s</b>\n      <p>%s</p>" % (preg, resp))
    return "\n".join(filas)


def enlaces_html(archivo_actual):
    filas = []
    for archivo, nombre, sub in TEMAS_NAV:
        if archivo == archivo_actual:
            continue
        filas.append('      <a class="tema" href="%s"><b>%s</b><span>%s</span></a>'
                     % (archivo, nombre, sub))
    return "\n".join(filas)


